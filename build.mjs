// Inline ./figures into one self-contained file: ./quadknob.js.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const figures = Object.fromEntries(readdirSync(new URL('figures/', here)).filter((file) => file.endsWith('.html')).sort()
  .map((file) => [file.replace(/\.html$/, ''), readFileSync(new URL(`figures/${file}`, here), 'utf8')]))
const source = readFileSync(new URL('src/quadknob.js', here), 'utf8')
if (!source.includes('/* global FIGURES */')) throw new Error('src/quadknob.js lost its FIGURES marker')
const out = source.replace('/* global FIGURES */', `const FIGURES = ${JSON.stringify(figures)}`)
writeFileSync(new URL('quadknob.js', here), `// Generated by build.mjs from src/quadknob.js and figures/. Do not edit.\n${out}`)
console.log(`quadknob.js: ${Object.keys(figures).join(', ')} (${(out.length / 1024).toFixed(1)} kB)`)
